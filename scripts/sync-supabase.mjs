#!/usr/bin/env node
// Copies the engine into supabase/functions/_shared/engine so the Edge Function
// runs exactly the same rules as the browser and the Node server.
// Run after changing anything in engine/:   node scripts/sync-supabase.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'engine');
const DST = path.join(ROOT, 'supabase/functions/_shared/engine');
fs.rmSync(DST, { recursive: true, force: true });
fs.mkdirSync(DST, { recursive: true });
for (const f of fs.readdirSync(SRC)) if (f.endsWith('.js')) fs.copyFileSync(path.join(SRC, f), path.join(DST, f));
const ck = JSON.parse(fs.readFileSync(path.join(SRC, 'checkpoints/default.json'), 'utf8'));
fs.writeFileSync(path.join(DST, 'checkpoint.js'), `// Generated by scripts/sync-supabase.mjs from engine/checkpoints/default.json — do not edit.\nexport const CHECKPOINT = ${JSON.stringify({ hash: ck.hash, weights: ck.weights })};\n`);
console.log(`synced engine -> ${path.relative(ROOT, DST)}`);
